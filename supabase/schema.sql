-- Ownership protection for all base tables.
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['foods','recipes','recipe_ingredients','meal_entries','daily_goals','meal_templates','meal_template_entries'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.%I TO authenticated', t);
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM anon', t);
    IF t <> 'daily_goals' THEN
      EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE public.%I_id_seq TO authenticated', t);
    END IF;
    EXECUTE format('DROP POLICY IF EXISTS %I_select_own ON public.%I', t, t);
    EXECUTE format('DROP POLICY IF EXISTS %I_insert_own ON public.%I', t, t);
    EXECUTE format('DROP POLICY IF EXISTS %I_update_own ON public.%I', t, t);
    EXECUTE format('DROP POLICY IF EXISTS %I_delete_own ON public.%I', t, t);
    EXECUTE format('CREATE POLICY %I_select_own ON public.%I FOR SELECT TO authenticated USING ((select auth.uid()) = user_id)', t, t);
    EXECUTE format('CREATE POLICY %I_insert_own ON public.%I FOR INSERT TO authenticated WITH CHECK ((select auth.uid()) = user_id)', t, t);
    EXECUTE format('CREATE POLICY %I_update_own ON public.%I FOR UPDATE TO authenticated USING ((select auth.uid()) = user_id) WITH CHECK ((select auth.uid()) = user_id)', t, t);
    EXECUTE format('CREATE POLICY %I_delete_own ON public.%I FOR DELETE TO authenticated USING ((select auth.uid()) = user_id)', t, t);
  END LOOP;
END $$;

-- Authenticated users may only own or reference rows from their own account.
DROP POLICY IF EXISTS recipe_ingredients_insert_own ON public.recipe_ingredients;
CREATE POLICY recipe_ingredients_insert_own ON public.recipe_ingredients FOR INSERT TO authenticated
  WITH CHECK ((select auth.uid()) = user_id AND EXISTS (SELECT 1 FROM public.recipes r WHERE r.id = recipe_id AND r.user_id = (select auth.uid())));
DROP POLICY IF EXISTS recipe_ingredients_update_own ON public.recipe_ingredients;
CREATE POLICY recipe_ingredients_update_own ON public.recipe_ingredients FOR UPDATE TO authenticated
  USING ((select auth.uid()) = user_id)
  WITH CHECK ((select auth.uid()) = user_id AND EXISTS (SELECT 1 FROM public.recipes r WHERE r.id = recipe_id AND r.user_id = (select auth.uid())));
