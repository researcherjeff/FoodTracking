create table if not exists public.foods (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null,
  serving_size text not null,
  calories integer not null default 0 check (calories >= 0),
  protein double precision not null default 0 check (protein >= 0),
  carbs double precision not null default 0 check (carbs >= 0),
  fat double precision not null default 0 check (fat >= 0),
  fiber double precision not null default 0 check (fiber >= 0),
  is_favorite boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.recipes (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null,
  servings integer not null default 1 check (servings >= 1),
  created_at timestamptz not null default now()
);

create table if not exists public.recipe_ingredients (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  recipe_id bigint not null references public.recipes(id) on delete cascade,
  food_id bigint references public.foods(id) on delete set null,
  food_name text not null,
  serving_size text not null,
  calories integer not null default 0,
  protein double precision not null default 0,
  carbs double precision not null default 0,
  fat double precision not null default 0,
  fiber double precision not null default 0,
  quantity double precision not null default 1 check (quantity >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.meal_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  food_id bigint references public.foods(id) on delete set null,
  date date not null,
  meal_type text not null check (meal_type in ('Breakfast', 'Lunch', 'Dinner', 'Snack')),
  servings double precision not null default 1 check (servings > 0),
  entry_type text not null default 'FOOD',
  recipe_id bigint,
  food_name text not null,
  serving_size text not null,
  calories integer not null default 0,
  protein double precision not null default 0,
  carbs double precision not null default 0,
  fat double precision not null default 0,
  fiber double precision not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.daily_goals (
  user_id uuid primary key default auth.uid() references auth.users(id) on delete cascade,
  calorie_goal integer not null default 2000 check (calorie_goal >= 0),
  protein_goal double precision not null default 100 check (protein_goal >= 0),
  carbs_goal double precision not null default 200 check (carbs_goal >= 0),
  fat_goal double precision not null default 65 check (fat_goal >= 0),
  fiber_goal double precision not null default 30 check (fiber_goal >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.meal_templates (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null,
  meal_type text not null default 'Dinner' check (meal_type in ('Breakfast', 'Lunch', 'Dinner', 'Snack')),
  created_at timestamptz not null default now()
);

create table if not exists public.meal_template_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  template_id bigint not null references public.meal_templates(id) on delete cascade,
  food_id bigint references public.foods(id) on delete set null,
  entry_type text not null default 'FOOD',
  recipe_id bigint,
  food_name text not null,
  serving_size text not null,
  servings double precision not null default 1 check (servings > 0),
  calories integer not null default 0,
  protein double precision not null default 0,
  carbs double precision not null default 0,
  fat double precision not null default 0,
  fiber double precision not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists foods_user_name_idx on public.foods(user_id, name);
