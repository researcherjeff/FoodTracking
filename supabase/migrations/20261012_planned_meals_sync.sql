-- FoodTracker v1.9.3: enable cross-device Weekly Planner synchronization.
-- Run this once in Supabase Dashboard -> SQL Editor while connected to the
-- same project configured in the Android app.

create table if not exists public.planned_meals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  template_id bigint not null references public.meal_templates(id) on delete cascade,
  planned_date date not null,
  meal_type text not null check (meal_type in ('Breakfast', 'Lunch', 'Dinner', 'Snack')),
  servings_multiplier numeric(4,2) not null default 1.00
    check (servings_multiplier >= 0.50 and servings_multiplier <= 2.00),
  created_at timestamptz not null default now()
);

create index if not exists planned_meals_user_date_idx
  on public.planned_meals (user_id, planned_date);
create index if not exists planned_meals_template_id_idx
  on public.planned_meals (template_id);

revoke all on table public.planned_meals from anon;
grant select, insert, update, delete on table public.planned_meals to authenticated;
grant usage, select on sequence public.planned_meals_id_seq to authenticated;

alter table public.planned_meals enable row level security;

drop policy if exists planned_meals_select_own on public.planned_meals;
drop policy if exists planned_meals_insert_own on public.planned_meals;
drop policy if exists planned_meals_update_own on public.planned_meals;
drop policy if exists planned_meals_delete_own on public.planned_meals;

create policy planned_meals_select_own on public.planned_meals
  for select to authenticated
  using ((select auth.uid()) = user_id);

create policy planned_meals_insert_own on public.planned_meals
  for insert to authenticated
  with check (
    (select auth.uid()) = user_id
    and exists (
      select 1
      from public.meal_templates mt
      where mt.id = planned_meals.template_id
        and mt.user_id = (select auth.uid())
    )
  );

create policy planned_meals_update_own on public.planned_meals
  for update to authenticated
  using ((select auth.uid()) = user_id)
  with check (
    (select auth.uid()) = user_id
    and exists (
      select 1
      from public.meal_templates mt
      where mt.id = planned_meals.template_id
        and mt.user_id = (select auth.uid())
    )
  );

create policy planned_meals_delete_own on public.planned_meals
  for delete to authenticated
  using ((select auth.uid()) = user_id);
