-- FoodTracker v1.10.5: sync grocery-list data across a user's devices.
-- Run once in Supabase Dashboard -> SQL Editor for the same project used by the app.

create table if not exists public.grocery_manual_items (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  week_start date not null,
  name text not null,
  quantity text not null default '',
  category text not null default 'Other',
  is_checked boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists grocery_manual_items_user_week_idx
  on public.grocery_manual_items (user_id, week_start);

revoke all on table public.grocery_manual_items from anon;
grant select, insert, update, delete on table public.grocery_manual_items to authenticated;
grant usage, select on sequence public.grocery_manual_items_id_seq to authenticated;
alter table public.grocery_manual_items enable row level security;

drop policy if exists grocery_manual_items_select_own on public.grocery_manual_items;
drop policy if exists grocery_manual_items_insert_own on public.grocery_manual_items;
drop policy if exists grocery_manual_items_update_own on public.grocery_manual_items;
drop policy if exists grocery_manual_items_delete_own on public.grocery_manual_items;

create policy grocery_manual_items_select_own on public.grocery_manual_items
  for select to authenticated using ((select auth.uid()) = user_id);
create policy grocery_manual_items_insert_own on public.grocery_manual_items
  for insert to authenticated with check ((select auth.uid()) = user_id);
create policy grocery_manual_items_update_own on public.grocery_manual_items
  for update to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
create policy grocery_manual_items_delete_own on public.grocery_manual_items
  for delete to authenticated using ((select auth.uid()) = user_id);

-- Recipe ingredients are stored as shopping-list snapshots. recipe_id is intentionally
-- not a foreign key so deleting or editing a recipe does not alter an existing list.
create table if not exists public.grocery_recipe_ingredients (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  week_start date not null,
  recipe_id bigint not null,
  recipe_name text not null,
  food_name text not null,
  serving_size text not null,
  quantity double precision not null default 0,
  category text not null default 'Other',
  created_at timestamptz not null default now()
);

create index if not exists grocery_recipe_ingredients_user_week_idx
  on public.grocery_recipe_ingredients (user_id, week_start);
create index if not exists grocery_recipe_ingredients_user_recipe_idx
  on public.grocery_recipe_ingredients (user_id, recipe_id);

